class CssEmitter(BaseEmitter):
    def emit(self, tokens, out_dir):
        colors = tokens["colors"]
        css_path = os.path.join(out_dir, "tokens.css")
        lines = [":root {"]
        for k, v in sorted(colors.items()):
            lines.append(f"  --color-{k}: {v};")
        lines.append("}\n")
        return {css_path: "\n".join(lines)}


def generate(design_file, root_dir, verify=False):
    tokens = parse_tokens(design_file)

    emitters = [
        (LvglThemeEmitter(), os.path.join(root_dir, "ui")),
        (CssEmitter(), os.path.join(root_dir, "ui/generated")),
    ]

    all_files = {}
    for emitter, target_dir in emitters:
        all_files.update(emitter.emit(tokens, target_dir))

    for path, content in all_files.items():
        if verify:
            if not os.path.exists(path):
                print(f"Verify failed: missing {path}", file=sys.stderr)
                return 1
            with open(path, "r", encoding="utf-8") as f:
                if f.read() != content:
                    print(f"Verify failed: {path} out of sync with DESIGN.md", file=sys.stderr)
                    return 1
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
            print(f"Emitted {path}")

    return 0


