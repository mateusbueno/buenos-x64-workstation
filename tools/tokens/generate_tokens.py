def strip_yaml_comment(line):
    in_single = False
    in_double = False
    for i, ch in enumerate(line):
        if ch == "'" and not in_double:
            in_single = not in_single
        elif ch == '"' and not in_single:
            in_double = not in_double
        elif ch == '#' and not in_single and not in_double:
            return line[:i].rstrip()
    return line.rstrip()


def safe_load_yaml(text):
    try:
        import yaml
        return yaml.safe_load(text)
    except ImportError:
        pass

    root = {}
    stack = [(root, -1)]
    for raw_line in text.splitlines():
        line = strip_yaml_comment(raw_line)
        if not line.strip():
            continue
        indent = len(raw_line) - len(raw_line.lstrip())
        content = line.strip()
        while len(stack) > 1 and indent <= stack[-1][1]:
            stack.pop()
        curr_container, _ = stack[-1]
        if content.startswith('- '):
            item = content[2:].strip().strip('\'"')
            if isinstance(curr_container, list):
                curr_container.append(item)
            continue
        if ':' in content:
            key, val = content.split(':', 1)
            key = key.strip().strip('\'"')
            val = val.strip()
            if not val:
                new_dict = {}
                if isinstance(curr_container, dict):
                    curr_container[key] = new_dict
                stack.append((new_dict, indent))
            else:
                val = val.strip('\'"')
                if isinstance(curr_container, dict):
                    curr_container[key] = val
    return root


def parse_tokens(design_md_path):
    with open(design_md_path, "r", encoding="utf-8") as f:
        content = f.read()

    m = re.match(r"^---\s*\n(.*?)\n---", content, re.DOTALL)
    if not m:
        raise ValueError(f"No YAML frontmatter in {design_md_path}")

    data = safe_load_yaml(m.group(1))
    return {
        "colors": data.get("colors", {}),
        "typography": data.get("typography", {}),
        "rounded": data.get("rounded", {}),
        "spacing": data.get("spacing", {}),
    }


def hex_to_uint(h):
    h = h.strip().lstrip('#')
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return f"0x{h.upper()}u"


