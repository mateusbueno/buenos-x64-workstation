#!/usr/bin/env python3
"""Writes organ_contacts.contacts (Story 2.5): the contact_k event list behind the multi-contact golden.

Format: see tools/offline-render/src/events_file.hpp. Times are milliseconds (up to three decimals) so the file is readable;
the renderer turns them into frames with integer arithmetic. Run:  python3 make_events.py organ_contacts.contacts (also writes organ_contacts_two.contacts)
Channel 0 = organ part 0, three contacts per key.
"""
import sys

lines = []
t = 0.0


def at(ms, text):
    lines.append((ms, len(lines), "%s %s" % (("%.3f" % ms).rstrip("0").rstrip(".") + "ms", text)))


def press(ms, note, spacing, ch=0, note_on=True, contacts=3):
    for k in range(1, contacts + 1):
        at(ms + (k - 1) * spacing, "close %d %d %d" % (ch, note, k))
    if note_on:
        at(ms + (contacts - 1) * spacing, "on %d %d 100" % (ch, note))


def lift(ms, note, spacing, ch=0, note_off=True, contacts=3):
    for i, k in enumerate(range(contacts, 0, -1)):
        at(ms + i * spacing, "open %d %d %d" % (ch, note, k))
    if note_off:
        at(ms + (contacts - 1) * spacing + 1, "off %d %d" % (ch, note))


# A. fast playing, 1 ms between contacts: a rolled chord, then released with 5 ms spacing
for i, n in enumerate((60, 64, 67, 72)):
    press(0.0 + 37.25 * i, n, 1.0)
for i, n in enumerate((60, 64, 67, 72)):
    lift(420.0 + 11.5 * i, n, 5.0)

# B. a slow smear: 20 ms between contacts going down, 20 ms going up, low note
press(560.0, 48, 20.0)
lift(900.0, 48, 20.0)

# C. half presses: contact 1 only; contacts 1-2, back up to 1, then down again; a skipped contact 2
at(1000.0, "close 0 55 1")
at(1060.0, "open 0 55 1")
at(1100.0, "close 0 55 1")
at(1110.0, "close 0 55 2")
at(1160.0, "open 0 55 2")
at(1220.0, "close 0 55 2")
at(1230.0, "close 0 55 3")
at(1300.0, "open 0 55 3")
at(1320.0, "open 0 55 2")
at(1340.0, "open 0 55 1")
at(1380.0, "close 0 57 1")
at(1390.0, "close 0 57 3")   # contact 2 skipped
at(1450.0, "open 0 57 2")    # opens 2 and, with it, the closed 3
at(1480.0, "open 0 57 1")

# D. malformed traffic, and a Note On/Off only key among it
at(1500.0, "open 0 62 1")        # open without close
at(1500.5, "close 0 62 3")       # close of 3 without 1
at(1501.0, "close 0 62 0")       # contact 0
at(1501.5, "close 0 62 4")       # beyond the keybed's 3
at(1502.0, "close 0 62 255")
at(1510.0, "on 0 40 100")        # a source with only Note On/Off: all busbars together
at(1560.0, "close 0 62 1")
at(1561.0, "close 0 62 1")       # duplicate close
at(1570.0, "close 0 62 2")
at(1620.0, "on 0 62 100")        # Note On after the contacts: no second voice
at(1700.0, "open 0 62 2")
at(1720.0, "open 0 62 1")
at(1730.0, "off 0 62")           # Note Off after the contacts opened: benign
at(1740.0, "off 0 62")
at(1750.0, "off 0 40")

# E. percussion fires on the first contact: single trigger, then re-armed
at(1800.0, "cc 0 80 127")        # percussion on (registry defaults: third harmonic, fast, soft)
press(1810.0, 52, 3.0, note_on=False)
press(1850.0, 59, 3.0)           # legato over 52: no percussion
lift(2000.0, 59, 3.0)
lift(2020.0, 52, 3.0, note_off=False)
press(2100.0, 52, 0.25)          # re-armed, very fast contacts (a quarter millisecond apart = 12 frames)
lift(2250.0, 52, 0.25)

lines.sort(key=lambda e: (e[0], e[1]))
out = ["# Story 2.5 golden input: contact_k event list (see tools/offline-render/src/events_file.hpp). Generated by make_events.py.",
       "contacts 3"] + [e[2] for e in lines]
open(sys.argv[1], "w").write("\n".join(out) + "\n")
# The same events for a 2-contact keybed (organ_contacts_two.contacts): contact 3 becomes out of range, the groups change; the
# golden test requires this render to differ from the 3-contact golden.
two = ["contacts 2" if l == "contacts 3" else l for l in out]
open(sys.argv[1].replace(".contacts", "_two.contacts"), "w").write("\n".join(two) + "\n")
