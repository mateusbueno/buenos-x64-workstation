#!/usr/bin/env bash
# Regenerates golden/<case>.wav (the untouched 16-bit sfizz_render output) and golden/<case>.case from
# the committed sfz/ and midi/ files, using the sfizz oracle (builds it first if needed, see
# tools/oracle/README.md). Needs network and a C++ toolchain the first time. Review the diff before
# committing: a changed golden means the oracle, the suite or the platform changed.
#
#   tools/offline-render/tests/sample_suite/regenerate_goldens.sh [case ...]
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
oracle="$here/../../../oracle"
mkdir -p "$here/golden"
want=("$@")
failed=0
while read -r name interp quality tol _ || [ -n "${name:-}" ]; do   # the last line may lack a newline
  [[ -z "${name:-}" || "$name" == \#* ]] && continue
  if [ ${#want[@]} -gt 0 ] && [[ ! " ${want[*]} " == *" $name "* ]]; then name=""; continue; fi
  echo "== $name (sfizz quality $quality)"
  rm -f "$here/golden/$name.wav" "$here/golden/$name.case"
  if ! "$oracle/render-oracle.sh" "$here/sfz/$name.sfz" "$here/midi/$name.mid" "$here/golden/$name.wav" "$quality" >/dev/null \
     || [ ! -s "$here/golden/$name.wav" ]; then
    echo "FAILED: $name (no golden written)" >&2
    rm -f "$here/golden/$name.wav" "$here/golden/$name.case"
    failed=$((failed + 1))
    name=""
    continue
  fi
  cat > "$here/golden/$name.case" <<CASE
# Generated by regenerate_goldens.sh from cases.txt. The reference is sfizz_render's own 16-bit output.
reference=$name.wav
tolerance_db=$tol
max_offset_frames=0
check_excess=1
reference_decode=sfizz-s16
CASE
  name=""
done < "$here/cases.txt"
[ "$failed" -eq 0 ] || { echo "$failed case(s) failed" >&2; exit 1; }
