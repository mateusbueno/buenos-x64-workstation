#!/usr/bin/env bash
# Regenerates golden/<case>.wav (FluidSynth's 16-bit output, trailing digital silence trimmed) and
# golden/<case>.case from the fixtures generated in code (sf2_suite_test --emit), using the FluidSynth
# oracle (builds it first if needed, see tools/oracle/README.md). Needs network and a C++ toolchain the first
# time. Review the diff before committing: a changed golden means the oracle, the suite or the platform changed.
#
#   tools/offline-render/tests/sf2_suite/regenerate_goldens.sh <cmake build dir> [case ...]
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
oracle="$here/../../../oracle"
[ $# -ge 1 ] || { echo "usage: $0 <cmake build dir> [case ...]" >&2; exit 2; }
build="$1"; shift
want=("$@")
exe="$build/tools/offline-render/sf2_suite_test"
[ -x "$exe" ] || { echo "build sf2_suite_test first: $exe" >&2; exit 2; }
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
"$exe" --emit "$tmp"
mkdir -p "$here/golden"
failed=0
while read -r name tol offs _ || [ -n "${name:-}" ]; do
  [[ -z "${name:-}" || "$name" == \#* ]] && continue
  if [ ${#want[@]} -gt 0 ] && [[ ! " ${want[*]} " == *" $name "* ]]; then continue; fi
  echo "== $name"
  # Everything is built in $tmp and moved into golden/ only when it is complete: a failure never touches a committed golden.
  if ! "$oracle/render-fluidsynth.sh" "$tmp/$name.sf2" "$tmp/$name.mid" "$tmp/$name.raw.wav"; then
    echo "FAILED: $name (golden left as it was)" >&2
    failed=$((failed + 1))
    continue
  fi
  # Trailing digital silence is cut (FluidSynth's player adds 2 s of grace after the last voice): the file
  # keeps 100 ms after its last non-zero frame. Nothing else is changed. An output that is entirely silent is an error.
  if ! python3 -I - "$tmp/$name.raw.wav" "$tmp/$name.wav" <<'PY'
import sys, wave
src, dst = sys.argv[1], sys.argv[2]
with wave.open(src, 'rb') as w:
    ch, sw, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
    data = w.readframes(n)
assert sw == 2 and ch == 2 and rate == 48000, (ch, sw, rate)
frame = ch * sw
last = n
while last > 0 and data[(last - 1) * frame:last * frame] == b'\0' * frame:
    last -= 1
if last == 0:
    sys.exit('the oracle rendered silence')
keep = min(n, last + 4800)
with wave.open(dst, 'wb') as o:
    o.setnchannels(ch); o.setsampwidth(sw); o.setframerate(rate)
    o.writeframes(data[:keep * frame])
PY
  then
    echo "FAILED: $name (silent or unreadable oracle output; golden left as it was)" >&2
    failed=$((failed + 1))
    continue
  fi
  cat > "$tmp/$name.case" <<CASE
# Generated by regenerate_goldens.sh from cases.txt. The reference is FluidSynth's own 16-bit output (trailing silence trimmed).
reference=$name.wav
tolerance_db=$tol
max_offset_frames=$offs
check_excess=1
CASE
  mv "$tmp/$name.wav" "$here/golden/$name.wav"
  mv "$tmp/$name.case" "$here/golden/$name.case"
done < "$here/cases.txt"
[ "$failed" -eq 0 ] || { echo "$failed case(s) failed" >&2; exit 1; }
