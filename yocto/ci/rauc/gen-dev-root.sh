#!/usr/bin/env bash
# Story 6.12/6.13: generates a RAUC signing root (ECDSA P-256, X.509 chain) of one named image variant in a directory OUTSIDE the repository.
#   gen-dev-root.sh [--variant dev|factory-test] [--out DIR] [--name NAME] [--force]
# --variant dev (default) and --variant factory-test (cannot be combined with --name; --name is for foreign test roots and may not be dev, factory-test, prod or production); any other variant, in particular production, is REFUSED: the production root is created only
# inside an offline HSM (tools/keys/KEY-HIERARCHY.md, Story 6.10), never by a script. The certificate subject carries the marker the image
# recipes check: "Velora <variant> RAUC root (not for production)". factory-test needs an explicit --out (its keys belong on the factory-test
# signing host, not in a developer's home directory) and its certificates are valid for 365 days (dev: 3650); regenerate per factory-test release.
# Default DIR: $XDG_DATA_HOME/velora-dev-keys/rauc, else ~/.velora-dev-keys/rauc (the same place as tools/keys/velora_keys.py; tools/keys/KEY-HIERARCHY.md,
# "RAUC bundle signing | dev"). NAME (default "dev") is only the certificate common name: the Docker test calls this twice (dev and foreign).
# Output (the private files are 0600; the directory is 0700):
#   ca.key.pem        root private key   (dev only; keep it here, never copy it into an image or the repository)
#   ca.cert.pem       root certificate   = the KEYRING baked into the image (VELORA_RAUC_KEYRING_FILE); public
#   signing.key.pem   bundle signing private key   (RAUC_KEY_FILE)
#   signing.cert.pem  bundle signing certificate, signed by the root (RAUC_CERT_FILE); public
#   DEV-ONLY.txt      label (also makes tools/ci/check_no_private_keys.py flag an accidental commit of this directory)
# No extendedKeyUsage on purpose: RAUC verifies with the S/MIME-signing purpose, which rejects a codeSigning-only certificate.
# Refuses a directory inside the repository and never overwrites without --force.
set -euo pipefail
OUT=""; NAME="dev"; VARIANT=""; NAME_SET=0; FORCE=0; DAYS=3650
while [ $# -gt 0 ]; do
  case "$1" in
    --out) OUT="$2"; shift 2;;
    --name) NAME="$2"; NAME_SET=1; shift 2;;
    --variant) VARIANT="$2"; shift 2;;
    --force) FORCE=1; shift;;
    -h|--help) sed -n '2,22p' "$0"; exit 0;;
    *) echo "unknown argument: $1" >&2; exit 2;;
  esac
done
if [ -n "$VARIANT" ] && [ "$NAME_SET" -eq 1 ]; then echo "--variant and --name cannot be combined (the variant is the certificate name)" >&2; exit 2; fi
if [ "$NAME_SET" -eq 1 ]; then
  # --name only labels foreign test roots: the names of the real variants (and production) come only through --variant
  case "$(printf '%s' "$NAME" | tr 'A-Z' 'a-z')" in
    dev|factory-test|prod|production) echo "refusing --name '$NAME': dev, factory-test, prod and production are reserved (use --variant dev|factory-test)" >&2; exit 2;;
  esac
fi
if [ -n "$VARIANT" ]; then
  case "$VARIANT" in
    dev|factory-test) NAME="$VARIANT";;
    *) echo "refusing variant '$VARIANT': only dev and factory-test roots are generated by this script (a production root exists only inside an offline HSM, Story 6.10)" >&2; exit 2;;
  esac
fi
if [ "$VARIANT" = "factory-test" ]; then
  DAYS=365
  if [ -z "$OUT" ]; then echo "--variant factory-test needs an explicit --out (a directory on the factory-test signing host, outside the repository)" >&2; exit 2; fi
fi
case "$NAME" in *[!A-Za-z0-9_-]*|"") echo "--name must match [A-Za-z0-9_-]+" >&2; exit 2;; esac
if [ -z "$OUT" ]; then
  if [ -n "${XDG_DATA_HOME:-}" ]; then OUT="$XDG_DATA_HOME/velora-dev-keys/rauc"; else OUT="$HOME/.velora-dev-keys/rauc"; fi
fi
REPO="$(cd "$(dirname "$0")/../../.." && pwd -P)"
OUT="$(python3 -c 'import os,sys; print(os.path.realpath(sys.argv[1]))' "$OUT")"
case "$OUT/" in "$REPO"/*) echo "refusing to write key material inside the repository ($REPO): use a directory outside it" >&2; exit 1;; esac
mkdir -p "$OUT"
if [ "$FORCE" -ne 1 ] && ls "$OUT"/*.pem >/dev/null 2>&1; then echo "$OUT already holds key material; pass --force to replace it" >&2; exit 1; fi
chmod 0700 "$OUT"
cd "$OUT"
umask 077
rm -f ca.key.pem ca.cert.pem signing.key.pem signing.cert.pem ca.srl
openssl ecparam -genkey -name prime256v1 -noout -out ca.key.pem
openssl req -x509 -new -key ca.key.pem -sha256 -days "$DAYS" -subj "/O=Velora/CN=Velora ${NAME} RAUC root (not for production)" \
  -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" -addext "subjectKeyIdentifier=hash" -out ca.cert.pem
openssl ecparam -genkey -name prime256v1 -noout -out signing.key.pem
openssl req -new -key signing.key.pem -subj "/O=Velora/CN=Velora ${NAME} RAUC bundle signing" -out signing.csr
printf 'basicConstraints=CA:FALSE\nkeyUsage=critical,digitalSignature\nsubjectKeyIdentifier=hash\nauthorityKeyIdentifier=keyid\n' > signing.ext
openssl x509 -req -in signing.csr -CA ca.cert.pem -CAkey ca.key.pem -CAcreateserial -sha256 -days "$DAYS" -extfile signing.ext -out signing.cert.pem 2>/dev/null
rm -f signing.csr signing.ext ca.srl
openssl verify -CAfile ca.cert.pem signing.cert.pem >/dev/null
chmod 0600 ca.key.pem signing.key.pem; chmod 0644 ca.cert.pem signing.cert.pem
# the first line is the marker text of tools/keys/velora_keys.py (assembled here so that this script itself does not trip the secret check)
if [ "$VARIANT" = "factory-test" ]; then
  printf 'FACTORY-TEST-ONLY %s (root=factory-test)\nRAUC factory-test signing root generated by yocto/ci/rauc/gen-dev-root.sh. Private keys stay on the factory-test signing host; never commit, never copy into an image: only ca.cert.pem goes into the image.\n' KEYS > FACTORY-TEST-ONLY.txt
else
  printf 'DEV-ONLY %s (root=dev)\nRAUC %s signing root generated by yocto/ci/rauc/gen-dev-root.sh. Never commit, never copy into an image: only ca.cert.pem goes into the image.\n' KEYS "$NAME" > DEV-ONLY.txt
fi
echo "wrote $OUT (keyring for the image: $OUT/ca.cert.pem)"
